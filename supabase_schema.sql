-- ── 1. Trips Table ───────────────────────────────────────────────────────────
-- Stores each user's saved trips.
-- The `itinerary` column stores the full AI-generated JSON as a JSONB object.
-- JSONB is a PostgreSQL type that lets you store and query JSON efficiently.

CREATE TABLE IF NOT EXISTS public.trips (
    -- Primary key: UUID generated by our backend (not Supabase auto-gen)
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Foreign key to auth.users — who owns this trip
    -- ON DELETE CASCADE: if a user deletes their account, their trips are also deleted
    user_id         UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,

    -- Trip metadata
    title           TEXT NOT NULL DEFAULT 'Untitled Trip',
    destination     TEXT NOT NULL,
    start_date      DATE NOT NULL,
    end_date        DATE NOT NULL,
    budget          NUMERIC(12, 2) NOT NULL DEFAULT 0,
    currency        TEXT NOT NULL DEFAULT 'USD',
    num_travelers   INTEGER NOT NULL DEFAULT 1,
    travel_style    TEXT NOT NULL DEFAULT 'mid-range',
    interests       TEXT[] NOT NULL DEFAULT '{}',    -- Array of interest tags
    special_requests TEXT,

    -- The full AI-generated itinerary stored as JSON
    -- JSONB is more efficient than TEXT for JSON queries
    itinerary       JSONB,

    -- User's personal notes about the trip
    notes           TEXT,

    -- Timestamps (timezone-aware)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── 2. Index for faster queries ───────────────────────────────────────────────
-- Without an index, "get all trips for user X" would scan the entire table.
-- This index makes it instant.

CREATE INDEX IF NOT EXISTS trips_user_id_idx ON public.trips (user_id);
CREATE INDEX IF NOT EXISTS trips_created_at_idx ON public.trips (created_at DESC);

-- ── 3. Enable Row Level Security (RLS) ───────────────────────────────────────
-- RLS is the key security feature. Without policies, NO ONE can access the table.
-- After enabling, we add policies that say exactly who can do what.

ALTER TABLE public.trips ENABLE ROW LEVEL SECURITY;

-- ── 4. RLS Policies ──────────────────────────────────────────────────────────
-- Each policy has a name, target operation, and a condition (USING clause).
-- auth.uid() is a Supabase built-in that returns the current user's UUID.

-- SELECT: users can only see their own trips
CREATE POLICY "Users can view own trips"
    ON public.trips
    FOR SELECT
    USING (auth.uid() = user_id);

-- INSERT: users can only create trips for themselves
CREATE POLICY "Users can create own trips"
    ON public.trips
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

-- UPDATE: users can only update their own trips
CREATE POLICY "Users can update own trips"
    ON public.trips
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- DELETE: users can only delete their own trips
CREATE POLICY "Users can delete own trips"
    ON public.trips
    FOR DELETE
    USING (auth.uid() = user_id);

-- ── 5. Service Role Bypass ────────────────────────────────────────────────────
-- Our backend uses the service_role key which automatically bypasses RLS.
-- This is intentional — the backend validates ownership in application code.
-- The anon and authenticated roles still respect RLS above.

-- ── 6. Auto-update `updated_at` trigger ──────────────────────────────────────
-- Automatically updates the updated_at column whenever a row is modified.

CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trips_updated_at
    BEFORE UPDATE ON public.trips
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

